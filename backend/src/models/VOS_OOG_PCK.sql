DROP TABLE IF EXISTS VOS_OOG_PCK;

CREATE TABLE VOS_OOG_PCK (
    PCK_ORD_SEQ INT(10) NOT NULL COMMENT '(PK) Upload Sequence',
    PCK_ITM_SEQ INT(10) NOT NULL COMMENT '(PK) Upload Item Sequence',
-- ----------------S: user-defined
    PCK_NO INT(10) NOT NULL COMMENT 'Packing Order No(display)',
    ITM_NM VARCHAR(255) DEFAULT NULL COMMENT 'Item Name',
    PCK_LEN DECIMAL(10, 2) DEFAULT NULL COMMENT 'Box Length',
    PCK_WDT DECIMAL(10, 2) DEFAULT NULL COMMENT 'Box Width',
    PCK_HGT DECIMAL(10, 2) DEFAULT NULL COMMENT 'Box Height',
    PCK_QTY INT(10) DEFAULT NULL COMMENT 'Box Quantity',
    PCK_WGT DECIMAL(12, 2) DEFAULT NULL COMMENT 'Box Weight',
    PCK_RMK VARCHAR(255) DEFAULT NULL COMMENT 'Packing Remarks',
    ESTM_PCK_LEN DECIMAL(10, 2) DEFAULT NULL COMMENT 'Estimated Box Length',
    ESTM_PCK_WDT DECIMAL(10, 2) DEFAULT NULL COMMENT 'Estimated Box Width',
    ESTM_PCK_HGT DECIMAL(10, 2) DEFAULT NULL COMMENT 'Estimated Box Height',
    PCK_CBM DECIMAL(10, 4) DEFAULT NULL COMMENT 'CBM Calculation Result',
    PCK_TP_CD VARCHAR(255) DEFAULT NULL COMMENT 'Packing Type Code (1:일반, 2:진공)',
    PCK_GRS_WGT DECIMAL(12, 2) DEFAULT NULL COMMENT 'Gross Weight',
-- ----------------E: user-defined
    CRE_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT 'Created Time',
    UPD_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT 'Updated Time',
    PRIMARY KEY (PCK_ORD_SEQ, PCK_ITM_SEQ)
) COMMENT = 'OOG Packing Information';
