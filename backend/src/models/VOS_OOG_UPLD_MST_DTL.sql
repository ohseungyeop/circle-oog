DROP TABLE IF EXISTS VOS_OOG_UPLD_DTL;
DROP TABLE IF EXISTS VOS_OOG_UPLD_MST;

CREATE TABLE VOS_OOG_UPLD_MST (
    PCK_ORD_SEQ INT AUTO_INCREMENT COMMENT '(PK) Upload Sequence(Upload 차수)',
    UPLD_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT 'Upload Time',
    FILE_PATH VARCHAR(255) COMMENT 'Upload File Path',
    ORGN_FILE_NM VARCHAR(255) COMMENT 'Original File Name',
    EMAIL VARCHAR(255) NOT NULL COMMENT 'Upload User Email',
    ACCESS_TOKEN CHAR(32) UNIQUE NOT NULL COMMENT 'Upload User Token',
    PRIMARY KEY (PCK_ORD_SEQ)
) COMMENT 'OOG Upload Master';

CREATE TABLE VOS_OOG_UPLD_DTL (
    PCK_ITM_SEQ INT AUTO_INCREMENT COMMENT '(PK) Upload Item Sequence',
    PCK_ORD_SEQ INT NOT NULL COMMENT 'Upload Sequence(Upload 차수)',
-- ----------------S: user-defined
    PCK_NO INT(10) NOT NULL COMMENT 'Packing Order No(display)',
    ITM_NM VARCHAR(255) DEFAULT NULL COMMENT 'Item Name',
    PCK_LEN DECIMAL(10, 2) DEFAULT NULL COMMENT 'Box Length',
    PCK_WDT DECIMAL(10, 2) DEFAULT NULL COMMENT 'Box Width',
    PCK_HGT DECIMAL(10, 2) DEFAULT NULL COMMENT 'Box Height',
    PCK_QTY INT(10) DEFAULT NULL COMMENT 'Box Quantity',
    PCK_WGT DECIMAL(12, 2) DEFAULT NULL COMMENT 'Box Weight',
    PCK_RMK VARCHAR(255) DEFAULT NULL COMMENT 'Packing Remarks',
    ESTM_PCK_LEN DECIMAL(10, 2) DEFAULT NULL COMMENT 'Estimated Box Length',
    ESTM_PCK_WDT DECIMAL(10, 2) DEFAULT NULL COMMENT 'Estimated Box Width',
    ESTM_PCK_HGT DECIMAL(10, 2) DEFAULT NULL COMMENT 'Estimated Box Height',
    PCK_CBM DECIMAL(10, 4) DEFAULT NULL COMMENT 'CBM Calculation Result',
    PCK_TP_CD VARCHAR(255) DEFAULT NULL COMMENT 'Packing Type Code (1:일반, 2:진공)',
    PCK_GRS_WGT DECIMAL(12, 2) DEFAULT NULL COMMENT 'Gross Weight',
-- ----------------E: user-defined
    PRIMARY KEY (PCK_ITM_SEQ),
    CONSTRAINT FK_PCK_ORD_SEQ FOREIGN KEY (PCK_ORD_SEQ) REFERENCES VOS_OOG_UPLD_MST(PCK_ORD_SEQ) ON DELETE CASCADE
) COMMENT 'OOG Upload Details';
