DROP TABLE IF EXISTS vos_oog_clp;

CREATE TABLE vos_oog_clp (
    PCK_CLP_SEQ INT NOT NULL AUTO_INCREMENT COMMENT '(PK) Clp Item Sequence',
    PCK_ORD_SEQ INT(10) NOT NULL COMMENT 'Upload Sequence(Upload 차수)',
-- ----------------S: user-defined
    CLP_NO INT(10) NOT NULL COMMENT 'Container Loading Plan No',
    BOX_NO INT(10) DEFAULT NULL COMMENT 'Original Item No',
    ITEM VARCHAR(255) DEFAULT NULL COMMENT 'Item Name',
    MC_LEN DECIMAL(10, 2) DEFAULT NULL COMMENT 'M/C Length',
    MC_WDT DECIMAL(10, 2) DEFAULT NULL COMMENT 'M/C Width',
    MC_HGT DECIMAL(10, 2) DEFAULT NULL COMMENT 'M/C Height',
    BOX_LEN DECIMAL(10, 2) DEFAULT NULL COMMENT 'Box Length',
    BOX_WDT DECIMAL(10, 2) DEFAULT NULL COMMENT 'Box Width',
    BOX_HGT DECIMAL(10, 2) DEFAULT NULL COMMENT 'Box Height',
    QTY INT(10) DEFAULT NULL COMMENT 'Box Quantity',
    CBM DECIMAL(10, 4) DEFAULT NULL COMMENT 'CBM Calculation Result',
    TYPE VARCHAR(255) DEFAULT NULL COMMENT 'Packing Type Code (1:일반, 2:진공)',
    NW DECIMAL(12, 2) DEFAULT NULL COMMENT 'Net Weight',
    GW DECIMAL(12, 2) DEFAULT NULL COMMENT 'Gross Weight',
    REMARKS VARCHAR(255) DEFAULT NULL COMMENT 'Packing Remarks',
    TPSZ VARCHAR(10) DEFAULT '40''HQ' COMMENT 'Dry40(40HQ), Flatrack(40FR), Dry20(20DR)',
    OVER_WGT_YN ENUM('Y', 'N') DEFAULT 'N' COMMENT 'Weight 초과 여부',
    OVER_WDT_YN ENUM('Y', 'N') DEFAULT 'N' COMMENT 'Width 초과 여부',
    OVER_HGT_YN ENUM('Y', 'N') DEFAULT 'N' COMMENT '40fr Height 초과 여부',
-- ----------------E: user-defined
    CRE_DT DATETIME DEFAULT CURRENT_TIMESTAMP() COMMENT 'Created Time',
    UPD_DT DATETIME DEFAULT CURRENT_TIMESTAMP() COMMENT 'Updated Time',
    PRIMARY KEY (PCK_CLP_SEQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='OOG Container Loading Plan Result';
