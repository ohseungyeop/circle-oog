CREATE TABLE core_tenant (
 tenant_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_code varchar(20) NOT NULL UNIQUE CHECK(tenant_code ~ '^[A-Z0-9_-]+$'),
 tenant_name varchar(160) NOT NULL CHECK(length(trim(tenant_name))>0), status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','INACTIVE')),
 version bigint NOT NULL DEFAULT 0 CHECK(version>=0)
);
CREATE TABLE core_role (
 role_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL REFERENCES core_tenant,
 role_code varchar(50) NOT NULL CHECK(role_code ~ '^[A-Z][A-Z0-9_]{0,49}$'), role_name varchar(100) NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','INACTIVE')), priority integer NOT NULL CHECK(priority>=0),
 UNIQUE(tenant_id,role_id), UNIQUE(tenant_id,role_code)
);
CREATE TABLE core_user_account (
 user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL REFERENCES core_tenant,
 role_id bigint NOT NULL, username varchar(120) NOT NULL CHECK(length(trim(username))>0), password_hash varchar(200) NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','INACTIVE','LOCKED')), token_version bigint NOT NULL DEFAULT 0 CHECK(token_version>=0),
 failed_attempts integer NOT NULL DEFAULT 0 CHECK(failed_attempts>=0), locked_until timestamptz,
 version bigint NOT NULL DEFAULT 0 CHECK(version>=0), UNIQUE(tenant_id,user_id), UNIQUE(tenant_id,username),
 FOREIGN KEY(tenant_id,role_id) REFERENCES core_role(tenant_id,role_id)
);
CREATE TABLE core_menu (
 menu_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL REFERENCES core_tenant,
 menu_key varchar(50) NOT NULL, menu_name varchar(100) NOT NULL, UNIQUE(tenant_id,menu_key), UNIQUE(tenant_id,menu_id)
);
CREATE TABLE core_role_menu (
 tenant_id bigint NOT NULL, role_id bigint NOT NULL, menu_id bigint NOT NULL,
 can_view boolean NOT NULL DEFAULT false, can_create boolean NOT NULL DEFAULT false, can_edit boolean NOT NULL DEFAULT false,
 can_delete boolean NOT NULL DEFAULT false, can_export boolean NOT NULL DEFAULT false,
 PRIMARY KEY(tenant_id,role_id,menu_id), FOREIGN KEY(tenant_id,role_id) REFERENCES core_role(tenant_id,role_id), FOREIGN KEY(tenant_id,menu_id) REFERENCES core_menu(tenant_id,menu_id)
);
CREATE TABLE core_session (
 session_id uuid PRIMARY KEY, user_id bigint NOT NULL, tenant_id bigint NOT NULL,
 access_jti uuid NOT NULL UNIQUE, refresh_hash char(64) NOT NULL UNIQUE CHECK(refresh_hash ~ '^[0-9a-f]{64}$'),
 expires_at timestamptz NOT NULL, revoked_at timestamptz, created_at timestamptz NOT NULL DEFAULT now(), token_version bigint NOT NULL CHECK(token_version>=0),
 FOREIGN KEY(tenant_id,user_id) REFERENCES core_user_account(tenant_id,user_id), CHECK(expires_at>created_at), CHECK(revoked_at IS NULL OR revoked_at>=created_at)
);
CREATE INDEX core_session_account_idx ON core_session(tenant_id,user_id,expires_at);
CREATE TABLE core_login_history (
 id bigserial PRIMARY KEY, tenant_id bigint REFERENCES core_tenant, user_id bigint, username varchar(120) NOT NULL,
 status varchar(30) NOT NULL CHECK(status IN ('SUCCESS','FAILURE','LOCKED','LOGOUT','REFRESH')), occurred_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(tenant_id,user_id) REFERENCES core_user_account(tenant_id,user_id), CHECK(user_id IS NULL OR tenant_id IS NOT NULL)
);
CREATE INDEX core_login_history_tenant_time_idx ON core_login_history(tenant_id,occurred_at DESC);
